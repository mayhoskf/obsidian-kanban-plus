'use strict';
// src/ のモジュールを 1 ファイルの main.js にまとめる。
// 各モジュールは本文をそのまま関数で包み、実行時に localRequire で遅延評価する。
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const srcDir = path.join(root, 'src');
const outPath = path.join(root, 'main.js');

// main.js 内の並び順。評価順は require で決まるため、この順序は出力の差分を安定させるためだけのもの
const MODULES = [
  'settings/store.cjs',
  'kanban/native-adapter.cjs',
  'appearance/board.css',
  'settings/tab.css',
  'todos/panel.css',
  'appearance/appearance.cjs',
  'todos/todos.cjs',
  'settings/tab.cjs',
  'main.cjs',
];

function moduleBody(name) {
  const text = fs.readFileSync(path.join(srcDir, name), 'utf8').replace(/\r\n/g, '\n');
  return name.endsWith('.css') ? `module.exports = ${JSON.stringify(text)};` : text;
}

const entries = MODULES.map(name =>
  `"${name}": function(module, exports, require) {\n${moduleBody(name)}\n}`);

const output = `'use strict';
// Generated by scripts/build.cjs. Edit src/ instead.
const externalRequire = require;
const path = externalRequire('path').posix;
const modules = {
${entries.join(',\n')}
};
const cache = Object.create(null);
function localRequire(id, parent = '.') {
  if (!id.startsWith('./') && !id.startsWith('../')) return externalRequire(id);
  const key = path.join(path.dirname(parent), id);
  if (!Object.hasOwn(modules, key)) throw new Error('Cannot find module ' + id + ' from ' + parent);
  if (!cache[key]) {
    const item = { exports: {} }; cache[key] = item;
    modules[key](item, item.exports, request => localRequire(request, key));
  }
  return cache[key].exports;
}
module.exports = localRequire('./main.cjs');
`;

fs.writeFileSync(outPath, output);
console.log(`wrote ${path.relative(root, outPath)}`);
